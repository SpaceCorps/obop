// Writes src/tokens.native.ts from the colour maths of @obop/ui (web/packages/ui/src/colors.ts)
// and the small table below. The web keeps its tokens in tokens.css; until the DTCG compiler of
// docs/spec/mobile.md 8.1 exists, this script is the second target, and src/tokens.test.ts reads
// tokens.css and fails when the two differ.
//
//   vp run generate:tokens
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  mixOklab,
  oklchToHex,
  ramp,
  resolveAccent,
  SIGNALS,
  SURFACES,
  type Oklch,
} from "../../ui/src/colors.ts";

/** The default accent of tokens.css (`--accent`). A tenant's accent is resolved at run time. */
export const DEFAULT_ACCENT = "#6d3fd0";

/** Neutral hue of the semantic greys (colors.ts NEUTRAL_HUE). */
const H = 265;
const o = (l: number, c: number): Oklch => ({ l, c, h: H });

/** The semantic greys that colors.ts does not export: the same `oklch()` literals as tokens.css. */
export const GREYS = {
  light: {
    surface2: o(0.978, 0.003),
    surface3: o(0.945, 0.006),
    border: o(0.915, 0.008),
    borderStrong: o(0.84, 0.012),
    borderControl: o(0.62, 0.016),
    text: o(0.2, 0.02),
    textMuted: o(0.47, 0.02),
    textSubtle: o(0.52, 0.02),
  },
  dark: {
    surface2: o(0.235, 0.014),
    surface3: o(0.275, 0.015),
    border: o(0.3, 0.015),
    borderStrong: o(0.4, 0.018),
    borderControl: o(0.56, 0.02),
    text: o(0.96, 0.005),
    textMuted: o(0.74, 0.018),
    textSubtle: o(0.66, 0.02),
  },
} as const;

/** The share of the signal colour in its soft tint (tokens.css `--success-soft` and the like). */
export const SOFT_PERCENT = { success: 14, warning: 16, danger: 13, info: 13 } as const;
/** The ramp step of a signal's fill and ink per mode (tokens.css `--success: var(--success-600)`). */
export const SIGNAL_STEPS = {
  light: { fill: 600, ink: 700 },
  dark: { fill: 400, ink: 300 },
} as const;

const MODES = ["light", "dark"] as const;
type Mode = (typeof MODES)[number];

function colors(mode: Mode) {
  const surface = SURFACES[mode].panel;
  const greys = Object.fromEntries(
    Object.entries(GREYS[mode]).map(([k, v]) => [k, oklchToHex(v)]),
  ) as Record<keyof (typeof GREYS)["light"], string>;
  const accent = resolveAccent(DEFAULT_ACCENT)[mode];
  const signals = Object.fromEntries(
    (Object.keys(SIGNALS) as (keyof typeof SIGNALS)[]).map((name) => {
      const r = ramp(SIGNALS[name].hue, SIGNALS[name].chroma);
      const fill = r[SIGNAL_STEPS[mode].fill];
      return [
        name,
        { fill, ink: r[SIGNAL_STEPS[mode].ink], soft: mixOklab(fill, surface, SOFT_PERCENT[name]) },
      ];
    }),
  ) as Record<keyof typeof SIGNALS, { fill: string; ink: string; soft: string }>;
  return {
    bg: SURFACES[mode].canvas,
    surface,
    ...greys,
    accentFill: accent.fill,
    accentInk: accent.ink,
    onAccent: accent.onFill,
    accentSoft: mixOklab(accent.fill, surface, 12),
    onDanger: mode === "light" ? "#ffffff" : "#0c0d12",
    ...signals,
  };
}

/** Scales in dp and sp. The web values are in rem (16 px) in tokens.css; the touch sizes are the app's own. */
export const SCALES = {
  space: { 1: 4, 2: 8, 3: 12, 4: 16, 5: 20, 6: 24, 8: 32, 10: 40, 12: 48, 16: 64 },
  // tokens.css: --radius 12; --radius-sm max(4, 0.5r); --radius-md max(5, 0.7r); --radius-xl 1.5r.
  radius: { sm: 6, md: 8.4, lg: 12, xl: 18, pill: 999 },
  fontSize: { xs: 12, sm: 13, md: 16, lg: 18, xl: 20, "2xl": 24, "3xl": 30, "4xl": 38, "5xl": 52 },
  lineHeight: { tight: 1.15, snug: 1.3, normal: 1.5 },
  fontWeight: { regular: "400", medium: "500", semibold: "600", bold: "700" },
  // Touch targets: at least 48 dp (docs/spec/mobile.md 8.7); the web's 36 px control is for a mouse.
  control: { height: 48, heightLg: 56, minTouch: 48, big: 176 },
} as const;

export function render(): string {
  const body = {
    light: colors("light"),
    dark: colors("dark"),
    ...SCALES,
    defaultAccent: DEFAULT_ACCENT,
  };
  return `// GENERATED by scripts/generate-tokens.ts from web/packages/ui/src/colors.ts. Do not edit by hand;
// run \`vp run generate:tokens\`. src/tokens.test.ts fails when this file and tokens.css differ.
export const tokens = ${JSON.stringify(body, null, 2)} as const;

export type Tokens = typeof tokens;
export type ColorMode = "light" | "dark";
type Signal = { readonly fill: string; readonly ink: string; readonly soft: string };
/** One mode's colours, with the hex strings widened so that light and dark have the same type. */
export type Palette = {
  readonly [K in keyof Tokens["light"]]: Tokens["light"][K] extends string ? string : Signal;
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = resolve(dirname(fileURLToPath(import.meta.url)), "../src/tokens.native.ts");
  writeFileSync(out, render());
  console.log(`wrote ${out}`);
}
